/**
 * Extracts Japan's coastline from Natural Earth 1:50m (public domain, via the
 * `world-atlas` package) and writes it out as ready-to-use SVG path data in a
 * local equirectangular projection, together with the projected positions of
 * the cities on the trip.
 *
 *   node scripts/build-japan-map.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as topojson from 'topojson-client';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const topo = JSON.parse(readFileSync(resolve(root, 'node_modules/world-atlas/countries-50m.json'), 'utf8'));
const countries = topojson.feature(topo, topo.objects.countries);
const japan = countries.features.find((f) => f.properties?.name === 'Japan');
if (!japan) throw new Error('Japan not found in the countries dataset');

/* --- projection ---------------------------------------------------------- */
// Equirectangular with a cos(lat) correction at the map's centre latitude.
// Over a country-sized area this is visually indistinguishable from Mercator
// and keeps the maths trivial.
const LAT0 = 37.5;
const K = Math.cos((LAT0 * Math.PI) / 180);
const px = (lon) => lon * K;
const py = (lat) => -lat;

// Work out the extent so we can normalise into a fixed viewBox.
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
const polygons = japan.geometry.type === 'Polygon' ? [japan.geometry.coordinates] : japan.geometry.coordinates;
for (const poly of polygons) {
  for (const ring of poly) {
    for (const [lon, lat] of ring) {
      const x = px(lon), y = py(lat);
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }
}

const W = 1000;
const scale = W / (maxX - minX);
const H = Math.round((maxY - minY) * scale);
const sx = (lon) => (px(lon) - minX) * scale;
const sy = (lat) => (py(lat) - minY) * scale;
const r2 = (n) => Math.round(n * 10) / 10;

/* --- path data ----------------------------------------------------------- */
// Rings smaller than a few pixels are dropped: they are islets that render as
// specks and only add weight.
const paths = [];
for (const poly of polygons) {
  for (const ring of poly) {
    const pts = ring.map(([lon, lat]) => [sx(lon), sy(lat)]);
    let rx0 = Infinity, ry0 = Infinity, rx1 = -Infinity, ry1 = -Infinity;
    for (const [x, y] of pts) {
      if (x < rx0) rx0 = x;
      if (x > rx1) rx1 = x;
      if (y < ry0) ry0 = y;
      if (y > ry1) ry1 = y;
    }
    if (rx1 - rx0 < 3 && ry1 - ry0 < 3) continue;
    paths.push('M' + pts.map(([x, y]) => `${r2(x)} ${r2(y)}`).join('L') + 'Z');
  }
}

/* --- the trip's cities --------------------------------------------------- */
const CITIES = [
  { id: 'tokyo', name: 'Tokyo', lat: 35.676, lon: 139.65, order: 1 },
  { id: 'osaka', name: 'Osaka', lat: 34.694, lon: 135.502, order: 2 },
  { id: 'hamamatsu', name: 'Hamamatsu', lat: 34.711, lon: 137.726, order: 3 },
  { id: 'hiroshima', name: 'Hiroshima', lat: 34.385, lon: 132.455, order: 4 },
  // Kyoto was a day trip out of Osaka on June 20, not an overnight base.
  { id: 'kyoto', name: 'Kyoto', lat: 35.011, lon: 135.768, order: 0, aside: true },
];
const cities = CITIES.map((c) => ({ ...c, x: r2(sx(c.lon)), y: r2(sy(c.lat)) }));

const out = `// GENERATED by scripts/build-japan-map.mjs — do not edit by hand.
// Japan coastline from Natural Earth 1:50m (public domain), projected to a
// local equirectangular grid and normalised to a ${W}x${H} viewBox.
export const VIEWBOX = '0 0 ${W} ${H}';
export const JAPAN_PATHS: string[] = ${JSON.stringify(paths)};
export interface MapCity { id: string; name: string; lat: number; lon: number; order: number; aside?: boolean; x: number; y: number }
export const MAP_CITIES: MapCity[] = ${JSON.stringify(cities)};
`;
writeFileSync(resolve(root, 'src/data/japan-map.ts'), out);
console.log(`japan map: ${paths.length} rings, viewBox 0 0 ${W} ${H}, ${(out.length / 1024).toFixed(1)} kB`);
