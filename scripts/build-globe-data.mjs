/**
 * Generates the dot-matrix land grid the hero globe renders.
 *
 * Source: Natural Earth 1:50m land polygons, public domain, shipped via the
 * `world-atlas` npm package. We rasterise it once at build time into a flat
 * list of [lat, lon] land points so the browser ships coordinates, not a
 * mapping library.
 *
 *   node scripts/build-globe-data.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as topojson from 'topojson-client';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const topo = JSON.parse(readFileSync(resolve(root, 'node_modules/world-atlas/land-50m.json'), 'utf8'));
const land = topojson.feature(topo, topo.objects.land);

/** Rings of every polygon, flattened to [ [ [lon,lat], ... ], ... ] */
const rings = [];
for (const feature of land.features ?? [land]) {
  const g = feature.geometry ?? feature;
  if (g.type === 'Polygon') rings.push(...g.coordinates);
  else if (g.type === 'MultiPolygon') for (const poly of g.coordinates) rings.push(...poly);
}

// Bounding boxes make the point-in-polygon sweep ~40x faster.
const boxes = rings.map((ring) => {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const [x, y] of ring) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return { minX, minY, maxX, maxY };
});

function inRing(ring, x, y) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function isLand(lon, lat) {
  for (let r = 0; r < rings.length; r++) {
    const b = boxes[r];
    if (lon < b.minX || lon > b.maxX || lat < b.minY || lat > b.maxY) continue;
    if (inRing(rings[r], lon, lat)) return true;
  }
  return false;
}

/**
 * Equal-area-ish sampling: step longitude by STEP / cos(lat) so dots stay
 * evenly spaced on the sphere instead of bunching at the poles.
 */
const STEP = 1.15;
const points = [];
for (let lat = -84; lat <= 84; lat += STEP) {
  const lonStep = STEP / Math.max(0.12, Math.cos((lat * Math.PI) / 180));
  for (let lon = -180; lon < 180; lon += lonStep) {
    if (isLand(lon, lat)) points.push(Math.round(lat * 100), Math.round(lon * 100));
  }
}

mkdirSync(resolve(root, 'src/data'), { recursive: true });
const out = `// GENERATED by scripts/build-globe-data.mjs — do not edit by hand.
// Natural Earth 1:50m land polygons (public domain) sampled to a ${STEP}° grid.
// Flat pairs of lat,lon stored as hundredths of a degree to keep the payload small.
export const LAND: Int16Array = new Int16Array(${JSON.stringify(points)});
export const LAND_POINT_COUNT = ${points.length / 2};
`;
writeFileSync(resolve(root, 'src/data/land.ts'), out);
console.log(`land dots: ${points.length / 2}  ·  ${(out.length / 1024).toFixed(1)} kB source`);

// Every country outline and shared border from Natural Earth's 1:110m map.
// 32767 separates polylines; coordinate pairs are [lat, lon] × 100.
const countries = JSON.parse(readFileSync(resolve(root, 'node_modules/world-atlas/countries-110m.json'), 'utf8'));
const mesh = topojson.mesh(countries, countries.objects.countries);
const borders = [];
for (const line of mesh.coordinates) {
  if (line.length < 2) continue;
  for (const [lon, lat] of line) borders.push(Math.round(lat * 100), Math.round(lon * 100));
  borders.push(32767, 32767);
}
const borderOut = `// GENERATED by scripts/build-globe-data.mjs — do not edit by hand.
// Natural Earth 1:110m country boundaries, public domain; [lat,lon] × 100.
// 32767,32767 separates polylines.
export const BORDERS: Int16Array = new Int16Array(${JSON.stringify(borders)});
`;
writeFileSync(resolve(root, 'src/data/borders.ts'), borderOut);
console.log(`border vertices: ${borders.length / 2}  ·  ${(borderOut.length / 1024).toFixed(1)} kB source`);
